import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
const dir='.launchguild-local';
const files=(await fs.readdir(dir)).filter(f=>/^[a-f0-9-]{36}\.json$/.test(f));
const jobs=await Promise.all(files.map(async f=>JSON.parse(await fs.readFile(`${dir}/${f}`,'utf8'))));
const owner=jobs.find(j=>j.run.status==='needs-review')?.owner;
if(!owner) throw Error('A real completed local run is required before capturing proof.');
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}, deviceScaleFactor:1});
// Reopen the existing task session in an isolated QA browser. Never export the cookie.
await context.addCookies([{name:'launchguild-local-session',value:owner,domain:'localhost',path:'/api/local-agent',httpOnly:true,sameSite:'Strict'}]);
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:3210/demo/agents');
await page.getByRole('heading',{name:'Smith’s take'}).waitFor();
await page.evaluate(()=>document.fonts.ready);
await page.screenshot({path:'media/screenshots/agents-real-1440.png',fullPage:true});
await page.reload();
await page.getByRole('heading',{name:'Smith’s take'}).waitFor();
await page.locator('.source-links button').first().click();
await page.getByRole('dialog').waitFor();
if(!(await page.getByRole('dialog').innerText()).includes('Salesforce')) throw Error('Exact source did not open');
await page.getByRole('button',{name:'Close dialog'}).click();
const busy=jobs.find(j=>j.owner===owner&&['queued','working'].includes(j.run.status));
if(busy){await page.getByRole('button',{name:new RegExp('^'+busy.run.role)}).first().click();await page.screenshot({path:'media/screenshots/agent-working-1440.png',fullPage:true});}
await page.goto('http://localhost:3210/demo');
await page.locator('.activity-trail').waitFor();
await page.locator('.world-art').evaluate(img=>img.decode());
await page.screenshot({path:'media/screenshots/town-redesigned-1440.png',fullPage:true});
await page.setViewportSize({width:390,height:900});
await page.screenshot({path:'media/screenshots/town-redesigned-390.png',fullPage:true});
await page.goto('http://localhost:3210/demo/agents');
await page.getByRole('heading',{name:'Smith’s take'}).waitFor();
await page.screenshot({path:'media/screenshots/agents-real-390.png',fullPage:true});
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
if(errors.length)throw Error(errors.join('\n'));
await fs.writeFile('artifacts/redesign-browser-proof.json',JSON.stringify({capturedAt:new Date().toISOString(),realRunIds:jobs.filter(j=>j.owner===owner&&j.run.status==='needs-review').map(j=>({role:j.run.role,requestId:j.run.requestId,status:j.run.status,tokens:j.run.tokens,inputHash:j.run.inputHash})),checks:['actual saved model result visible','result survives refresh','source button opens source text','mobile has no page overflow','no page errors'],browser:'isolated Chromium verification of existing local task session'},null,2));
await browser.close();
console.log('Captured desktop and mobile UI with real stored results; reload and source links verified.');
